/**
 * Storage URL helpers.
 *
 * Pure string builders — no Supabase client and no secrets, so this module is
 * safe to import from Server Components, client components and the data
 * modules in `src/lib/data` alike. `@/lib/supabase` holds the service-role
 * client and must stay server-side; it re-exports everything here.
 */

const SUPABASE_PROJECT_URL =
  process.env.NEXT_PUBLIC_SUPABASE_URL ??
  "https://ipmdyrxfptdsulfhxjkb.supabase.co";

/**
 * Public base URL for all CDN-read media, without a trailing slash.
 *
 * **This is the cached-egress switch.** Set it to a Tigris bucket domain and every
 * PDF and content image the public site reads is served from a host with no egress
 * billing; leave it unset and every URL is built against Supabase exactly as before.
 * Object keys mirror the Supabase bucket layout (`<base>/pdfs/…`,
 * `<base>/avatars/optimized/…`), so the migration script can copy paths across
 * without rewriting a single data module.
 *
 * Nothing about writes or auth moves: `/api/upload` still puts avatars in Supabase
 * (upload is ingress, which is not metered) and the registration flow reads no
 * storage URLs at all, so a half-finished cutover cannot break it.
 */
const MEDIA_BASE_URL = (
  process.env.NEXT_PUBLIC_MEDIA_BASE_URL ?? ""
).replace(/\/+$/, "");

/** `true` when media is served from the external host rather than Supabase. */
export const usesExternalMediaHost = MEDIA_BASE_URL.length > 0;

/** Percent-encode an object key segment-wise, keeping its slashes. */
function encodeObjectKey(key: string): string {
  return key.split("/").map(encodeURIComponent).join("/");
}

export const AVATARS_BUCKET = "avatars";

/**
 * Public bucket holding the club's documents — syllabus PDFs today.
 *
 * Object keys are the human filenames the club uploads with (see
 * `publishedSyllabi` in `src/lib/data/syllabus.ts`), so this bucket is not
 * content-addressed the way `avatars` is: replacing a syllabus means replacing
 * the object under the same key.
 */
export const PDFS_BUCKET = "pdfs";

/** Public, CDN-served URL for an arbitrary object in a bucket. */
export function storagePublicUrl(bucket: string, path: string): string {
  const key = encodeObjectKey(`${bucket}/${path}`);
  if (usesExternalMediaHost) return `${MEDIA_BASE_URL}/${key}`;
  return `${SUPABASE_PROJECT_URL}/storage/v1/object/public/${key}`;
}

/**
 * Public URL for a document in the `pdfs` bucket — the **only** URL any page may
 * link for a given object.
 *
 * Supabase's CDN caches per full URL, and `?download` is the suffix that makes it
 * answer with `Content-Disposition: attachment`. Minting one canonical string per
 * object is deliberate: a page that also links the bare form stores the same
 * multi-megabyte PDF twice at the edge and pays a cold origin pull for whichever
 * variant nobody has clicked yet.
 *
 * On the external host the disposition header is set on the object at upload time
 * (see `scripts/migrate-media-to-tigris.mjs`), so the bare key is the canonical URL
 * and the query suffix would only add a second cache key.
 */
export function pdfUrl(path: string): string {
  const url = storagePublicUrl(PDFS_BUCKET, path);
  return usesExternalMediaHost ? url : `${url}?download`;
}

/**
 * URL for a pre-optimised WebP asset under `optimized/` in the avatars bucket.
 *
 * These are generated by `scripts/optimize-bucket-images.mjs` at exactly the
 * size they are displayed (2x for retina), so they are served verbatim and
 * never touch the Next.js image optimizer — no Vercel image transformations,
 * and the objects carry an immutable one-year `cache-control`.
 */
export function bucketImage(path: string): string {
  return storagePublicUrl(AVATARS_BUCKET, `optimized/${path}`);
}

/** Public URL for an object served from `avatars` exactly as it was uploaded. */
export function bucketOriginal(path: string): string {
  return storagePublicUrl(AVATARS_BUCKET, path);
}

/** Uploads that are already the final, small bytes (what the forms write). */
const ALREADY_SMALL = /\.(webp|avif)$/i;

/**
 * URL for a content image, named by its **original** path in the avatars bucket
 * (`"adminimages/abrar.png"`) rather than by the URL the browser should fetch.
 *
 * This is the egress switch for everything in `src/lib/data`: originals are
 * 0.5–9 MB and, because `avatars` is public and CDN-cached, each one is billed
 * again as cached egress on every card that renders it. `contentImage` points at
 * the WebP that `scripts/optimize-bucket-images.mjs` pre-encoded at display size
 * (9.4 MB → 28 KB) with an immutable one-year cache. Already-small uploads
 * (`.webp`/`.avif`) are served verbatim — they need no re-encode.
 *
 * The `<original>.<ext>.webp` suffix is the optimizer's target convention
 * (`TARGET_PREFIX + sourcePath.replace(/\\.([^.]+)$/, ".$1.webp")`); keep the two
 * in step if that ever changes, otherwise the card 404s.
 */
export function contentImage(path: string): string {
  if (ALREADY_SMALL.test(path)) return bucketOriginal(path);
  return bucketImage(`${path}.webp`);
}

/**
 * `true` when a public-object URL already points at a WebP under `optimized/`,
 * i.e. the final display bytes produced by `scripts/optimize-bucket-images.mjs`.
 * Those objects carry an immutable one-year cache and are already the size the
 * browser wants — transforming them again is pure wasted egress.
 */
export function isOptimizedObjectUrl(url: string): boolean {
  return /\/avatars\/optimized\//.test(url);
}

/**
 * Turn a Supabase *public object* URL into a *render* URL, so Supabase's own
 * CDN performs the resize/encode instead of Vercel's image optimizer.
 *
 * **Egress guard.** An object that is already pre-optimised (`optimized/*`,
 * produced by the bucket script) is returned **untouched** — the `render/image`
 * endpoint would otherwise pull the original back out of storage and re-encode on
 * every request, which is the single largest driver of metered egress in this
 * project. Only genuinely multi-megabyte *originals* that are not yet optimised
 * should be forced through the transform.
 *
 * Returns the input untouched when it isn't a public object URL — which includes
 * every URL on the external media host: Supabase's transform cannot read a Tigris
 * bucket, so those objects are served as the final bytes the migration uploaded.
 */
export function renderedImageUrl(
  url: string,
  options: { width: number; height?: number; quality?: number },
): string {
  if (isOptimizedObjectUrl(url)) return url;

  const match =
    /^(https?:\/\/[^/]+)\/storage\/v1\/object\/public\/(.+)$/.exec(url);
  if (!match) return url;

  const params = new URLSearchParams({
    width: String(options.width),
    resize: "cover",
    quality: String(options.quality ?? 80),
    format: "webp",
  });
  if (options.height) params.set("height", String(options.height));

  return `${match[1]}/storage/v1/render/image/public/${match[2]}?${params.toString()}`;
}

/**
 * Resolve a stored avatar/profile image to the URL that should actually be sent to
 * the browser, choosing the cheapest option that still looks right.
 *
 * - A URL that is **already optimised** (`optimized/*`, or a small immutable
 *   upload such as the 512px WebP `profile-form`/`/api/upload` produce) is
 *   served **directly** — no `render/image` transform, so Supabase never re-pulls
 *   the original for it.
 * - A raw legacy original is forced through `render/image` once per distinct width
 *   so the browser gets a small 2x WebP instead of a multi-megabyte file.
 *
 * Prefer this over calling `renderedImageUrl` by hand on stored avatar URLs: it
 * centralises the "is this already small?" decision that used to be split across
 * the profile form and the blog author card, and it is what keeps new uploads off
 * the metered transform path at all.
 */
export function avatarUrl(
  url: string | null | undefined,
  width: number,
): string | null {
  if (!url) return null;
  // Blob previews are client-in-memory and can never be touched by a CDN.
  if (url.startsWith("blob:")) return url;
  // Already-final bytes → serve verbatim.
  if (isOptimizedObjectUrl(url)) return url;
  // A UUID-named upload in the avatars root is what `/api/upload` writes — the
  // profile form compresses it to ≤512px WebP before the request, so it is
  // already small and immutable. Serving it directly bypasses the transform.
  if (/\/avatars\/[0-9a-f-]{36}\.(webp|png|jpe?g)$/.test(url)) return url;
  // Everything else is treated as a raw legacy original → resize once via CDN.
  return renderedImageUrl(url, { width });
}

